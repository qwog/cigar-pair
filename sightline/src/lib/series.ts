/** Categorical slots, assigned in fixed order and never cycled past eight. */
export const SERIES = [
  "var(--series-1)",
  "var(--series-2)",
  "var(--series-3)",
  "var(--series-4)",
  "var(--series-5)",
  "var(--series-6)",
  "var(--series-7)",
  "var(--series-8)",
] as const;

export const seriesColor = (slot: number) => SERIES[slot % SERIES.length]!;
